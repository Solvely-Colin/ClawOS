grep -Fq "json 'Controller offline'" "$root/usr/lib/clawos/clawos-panel-status"
grep -Fq 'Review approvals", ["/usr/lib/clawos/clawos-approval"]' "$root/usr/lib/clawos/clawos-agent-shelf"
grep -Fq 'clawos_attention.py' "$attention_status"
