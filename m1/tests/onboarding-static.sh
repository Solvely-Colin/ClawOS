grep -Fq 'clawos-attention-status' "$root/etc/clawos/waybar/config.jsonc"
grep -Fq 'clawos-intent-palette' "$root/etc/clawos/waybar/config.jsonc"
grep -Fq 'clawos-activity-action' "$root/etc/clawos/waybar/config.jsonc"
! grep -Fq '"on-click": "/usr/lib/clawos/clawos-app-palette"' "$root/etc/clawos/waybar/config.jsonc"
