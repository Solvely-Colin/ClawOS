grep -Fq 'resize set width $width px height $height px, move position 0 0' "$surface"
grep -Fq 'launch-prefix=/usr/lib/clawos/clawos-app-from-fuzzel' "$root/etc/clawos/fuzzel.ini"
grep -Fq 'case "app.list"' "$surfaced"
grep -Fq 'case "app.open"' "$surfaced"
grep -Fq 'resolveApplication' "$surfaced"
grep -Fq '["con", "floating_con"].includes(node.type)' "$surfaced"
grep -Fq 'allowHalfOpen: true' "$surfaced"
grep -Fq 'floating_maximum_size -1 x -1' "$root/etc/clawos/sway.conf"
grep -Fq 'spawn("/usr/bin/gio", ["launch", application.filePath]' "$app_registry"
grep -Fq 'X-ClawOS-AppId=web:gmail' "$root/usr/share/applications/clawos-gmail.desktop"
