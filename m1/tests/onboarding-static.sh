grep -Fq '"config", "set", "browser.enabled", "true", "--strict-json"' "$onboard_server"
grep -Fq '"config", "set", "plugins.entries.browser.enabled", "true", "--strict-json"' "$onboard_server"
grep -Fq '"config", "get", "tools.allow"' "$onboard_server"
grep -Fq '"config", "set", policyKey, JSON.stringify(merged), "--strict-json"' "$onboard_server"
grep -Fq '"plugins.entries.clawos-system.hooks.allowConversationAccess", "true", "--strict-json"' "$onboard_server"
grep -Fq '"plugins.entries.clawos-system.hooks.allowPromptInjection", "true", "--strict-json"' "$onboard_server"
grep -Fq 'saveOpenClawEnv("OPENCLAW_GATEWAY_TOKEN"' "$onboard_server"
grep -Fq '"--secret-input-mode", "ref"' "$onboard_server"
grep -Fq '"--gateway-token-ref-env"' "$onboard_server"
