test -x "$root/usr/lib/clawos/clawos-security-mode"
bash -n "$root/usr/lib/clawos/clawos-security-mode"
grep -Fq 'security.level.configure' "$onboard_server"
grep -Fq 'output Virtual-1 mode 1440x900 scale 1' "$root/etc/clawos/sway.conf"
grep -Fq 'gateway.remote.url' "$node_install"
grep -Fq 'ws://127.0.0.1:$port' "$node_install"
grep -Fq 'umask 077' "$browser"
grep -Fq 'file://$bootstrap' "$browser"
grep -Fq 'gateway_token gateway.auth.token' "$browser"
grep -Fq 'read_openclaw_env OPENCLAW_GATEWAY_TOKEN' "$browser"
if grep -Eq 'config get gateway\.(auth|remote)\.token' "$browser"; then
  echo "ClawOS browser must not use OpenClaw's redacted config output as a token." >&2
  exit 1
fi
grep -Fq 'cp -a /usr/lib/node_modules/openclaw' "$installer"
grep -Fq 'openclaw --version | grep -Fq "$OPENCLAW_VERSION"' "$installer"
! grep -Fq 'npm install --global' "$installer"
grep -Fq 'umask 022' "$installer"
grep -Fq 'runuser -u clawos -- openclaw --version' "$installer"
grep -Fq 'chromium foot fuzzel sway swaybg waybar' "$root/usr/lib/clawos/clawos-install-packages.sh"
grep -Fq '/usr/share/applications/clawos-gmail.desktop' "$installer"
grep -Fq 'clawos-app-from-fuzzel' "$installer"
grep -Fq 'Inspect system' "$live_welcome"
grep -Fq 'The full Agent workspace is created after installation.' "$live_welcome"
