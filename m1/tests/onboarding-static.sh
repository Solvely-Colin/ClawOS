  echo "The agent owns surface lifecycle; the panel must not advertise app launch buttons." >&2
  exit 1
fi
if grep -Fq 'sway/workspaces' "$root/etc/clawos/waybar/config.jsonc"; then
  echo "Fixed application workspaces are not the ClawOS navigation model." >&2
  exit 1
fi
grep -Fq '"on-click": "/usr/lib/clawos/clawos-power-menu"' "$root/etc/clawos/waybar/config.jsonc"
if grep -Fq 'custom/system' "$root/etc/clawos/waybar/config.jsonc"; then
  echo "The ClawOS wordmark owns the system menu; a second System module is not allowed." >&2
  exit 1
fi
grep -Fq 'Restarting ClawOS' "$root/usr/share/plymouth/themes/clawos/clawos.script"
grep -Fq 'passwd --root "$mount_root" --stdin clawos <"$key_file"' "$installer"
if grep -Fq 'getty@tty1.service.d/autologin.conf' "$installer"; then
  echo "The graphical ClawOS path must not fall through to a tty1 root autologin." >&2
  exit 1
fi
grep -Fq 'clawos-install-node' "$entry"
grep -Fq 'clawos-enroll-local-node' "$entry"
grep -Fq 'securityLevel // "full-root"' "$node_enroll"
grep -Fq 'node identity --json' "$node_enroll"
grep -Fq 'devices list --json' "$node_enroll"
grep -Fq 'nodes pending --json' "$node_enroll"
grep -Fq 'index("clawos.system")' "$node_enroll"
grep -Fq 'clawos-gateway-watchdog "$$"' "$browser"
